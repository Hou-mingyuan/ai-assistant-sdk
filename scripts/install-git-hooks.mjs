#!/usr/bin/env node
/**
 * install-git-hooks
 * -----------------
 * 用法：
 *   node scripts/install-git-hooks.mjs           # 安装（不覆盖已有的非托管 hook）
 *   node scripts/install-git-hooks.mjs --force   # 强制覆盖任何已有 hook
 *   node scripts/install-git-hooks.mjs --uninstall # 卸载（只在确认是本脚本写的 shim 时才删）
 *
 * 行为：
 * - 在 `.git/hooks/pre-commit` 写一个 POSIX shim，shim 调 `scripts/git-hooks/pre-commit.mjs`。
 * - shim 自带标记串 `# ai-assistant-sdk:managed-hook`，因此可以自动识别我们写的版本，避免误删用户自定义 hook。
 * - 跨平台：Git for Windows 自带 sh.exe 来跑 shim；Linux/macOS 直接跑。
 * - 退出码：0 = 成功，1 = 失败（含拒绝覆盖、找不到 .git）。
 */

import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const HOOK_MARKER = '# ai-assistant-sdk:managed-hook';

const SHIM_TEMPLATE = `#!/bin/sh
${HOOK_MARKER}
# Auto-generated by scripts/install-git-hooks.mjs — DO NOT EDIT BY HAND.
# To customize, edit scripts/git-hooks/pre-commit.mjs and re-run the installer.
# To bypass once: \`git commit --no-verify\`.

# Resolve repo root via the hook path (works on both Linux/macOS and Git Bash on Windows).
HOOK_DIR=$(dirname "$0")
REPO_ROOT=$(cd "$HOOK_DIR/../.." && pwd)
NODE_BIN=$(command -v node 2>/dev/null || echo node)

exec "$NODE_BIN" "$REPO_ROOT/scripts/git-hooks/pre-commit.mjs" "$@"
`;

function color(text, c) {
  if (process.env.NO_COLOR || !process.stdout.isTTY) return text;
  const codes = { red: 31, green: 32, yellow: 33, cyan: 36, gray: 90 };
  return `\x1b[${codes[c] ?? 0}m${text}\x1b[0m`;
}

function resolveGitDir(repoRoot) {
  /**
   * Use git itself to find the actual hooks dir.
   * Handles worktrees, GIT_DIR override, submodules, etc.
   */
  try {
    const out = execSync('git rev-parse --git-path hooks', {
      cwd: repoRoot,
      encoding: 'utf-8',
    }).trim();
    return path.resolve(repoRoot, out);
  } catch {
    return null;
  }
}

function isOurShim(content) {
  return typeof content === 'string' && content.includes(HOOK_MARKER);
}

function main() {
  const args = new Set(process.argv.slice(2));
  const force = args.has('--force');
  const uninstall = args.has('--uninstall');

  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const repoRoot = path.resolve(scriptDir, '..');
  const hooksDir = resolveGitDir(repoRoot);

  if (!hooksDir) {
    console.error(color('✗ Not inside a git repository (or git is not installed).', 'red'));
    console.error(color(`  Resolved repo root: ${repoRoot}`, 'gray'));
    process.exit(1);
  }

  const preCommitPath = path.join(hooksDir, 'pre-commit');

  if (uninstall) {
    if (!fs.existsSync(preCommitPath)) {
      console.log(color('✓ Nothing to uninstall (no pre-commit hook installed).', 'green'));
      return;
    }
    const current = fs.readFileSync(preCommitPath, 'utf-8');
    if (!isOurShim(current) && !force) {
      console.error(
        color(
          '✗ Refusing to remove existing pre-commit hook — it was not installed by this script.',
          'red',
        ),
      );
      console.error(color('  Use --force to remove it anyway, or delete it manually.', 'gray'));
      process.exit(1);
    }
    fs.unlinkSync(preCommitPath);
    console.log(color(`✓ Uninstalled pre-commit hook at ${preCommitPath}`, 'green'));
    return;
  }

  if (fs.existsSync(preCommitPath)) {
    const current = fs.readFileSync(preCommitPath, 'utf-8');
    if (isOurShim(current)) {
      if (current === SHIM_TEMPLATE) {
        console.log(color('✓ pre-commit hook already installed and up-to-date.', 'green'));
        return;
      }
      fs.writeFileSync(preCommitPath, SHIM_TEMPLATE);
      tryChmod(preCommitPath);
      console.log(color('✓ pre-commit hook refreshed (shim updated).', 'green'));
      return;
    }
    if (!force) {
      console.error(
        color(
          '✗ A pre-commit hook already exists and was NOT installed by this script.',
          'red',
        ),
      );
      console.error(color(`  Path: ${preCommitPath}`, 'gray'));
      console.error(
        color(
          '  Pass --force to overwrite, or back it up and re-run the installer.',
          'gray',
        ),
      );
      process.exit(1);
    }
  }

  fs.mkdirSync(hooksDir, { recursive: true });
  fs.writeFileSync(preCommitPath, SHIM_TEMPLATE);
  tryChmod(preCommitPath);
  console.log(color(`✓ pre-commit hook installed at ${preCommitPath}`, 'green'));
  console.log(color(`  Logic lives in scripts/git-hooks/pre-commit.mjs`, 'cyan'));
  console.log(color(`  Bypass for one commit: git commit --no-verify`, 'gray'));
}

function tryChmod(file) {
  /* On Windows chmod is a no-op but harmless. */
  try {
    fs.chmodSync(file, 0o755);
  } catch {
    /* ignore */
  }
}

main();
